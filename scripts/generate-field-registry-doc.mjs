import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = path.join(rootDir, 'contracts/field-registry.yml');
const outputPath = path.join(rootDir, 'contracts/generated/field-registry.md');

function parseScalar(value) {
  const trimmed = value.trim();
  if (trimmed === 'true') return true;
  if (trimmed === 'false') return false;
  if (trimmed === 'null') return null;
  if (/^-?\d+(\.\d+)?$/.test(trimmed)) return Number(trimmed);
  const quoted = trimmed.match(/^"(.*)"$/) || trimmed.match(/^'(.*)'$/);
  return quoted ? quoted[1] : trimmed;
}

function parseSimpleYaml(content) {
  const root = {};
  const stack = [{ indent: -1, value: root }];

  for (const rawLine of content.split(/\r?\n/)) {
    if (!rawLine.trim() || rawLine.trimStart().startsWith('#')) continue;

    const indent = rawLine.match(/^ */)[0].length;
    const line = rawLine.trim();
    const separatorIndex = line.indexOf(':');
    if (separatorIndex === -1) {
      throw new Error(`Invalid registry line: ${rawLine}`);
    }

    const key = line.slice(0, separatorIndex).trim().replace(/^["']|["']$/g, '');
    const rest = line.slice(separatorIndex + 1).trim();

    while (stack.length > 1 && indent <= stack.at(-1).indent) {
      stack.pop();
    }

    const parent = stack.at(-1).value;
    if (rest === '') {
      parent[key] = {};
      stack.push({ indent, value: parent[key] });
    } else {
      parent[key] = parseScalar(rest);
    }
  }

  return root;
}

function escapeCell(value) {
  return String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, '<br>');
}

function renderFieldTable(fields) {
  const lines = [
    '| Field | Type | Required | Source | Description |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const [name, field] of Object.entries(fields ?? {})) {
    lines.push(
      `| \`${escapeCell(name)}\` | ${escapeCell(field.type)} | ${escapeCell(field.required)} | ${escapeCell(
        field.source,
      )} | ${escapeCell(field.description)} |`,
    );
  }

  return lines.join('\n');
}

function renderRegistry(registry) {
  const lines = [
    '<!-- GENERATED FILE. Do not edit directly. -->',
    '<!-- Source: contracts/field-registry.yml -->',
    '<!-- Generated by: node scripts/generate-field-registry-doc.mjs -->',
    '',
    '# Field Registry',
    '',
    registry.summary,
    '',
    '## Objects',
    '',
  ];

  for (const [name, object] of Object.entries(registry.objects ?? {})) {
    lines.push(`### ${name}`, '');
    lines.push(object.summary ?? '', '');
    lines.push(`- Lifecycle node: ${object.lifecycleNode ?? '-'}`);
    lines.push(`- Core object: ${object.coreObject ?? '-'}`);
    lines.push(`- Owner: ${object.owner ?? '-'}`);
    lines.push('', renderFieldTable(object.fields), '');
  }

  lines.push('## Forbidden Fields', '');
  lines.push('| Pattern | Reason |');
  lines.push('| --- | --- |');

  for (const field of Object.values(registry.forbiddenFields ?? {})) {
    lines.push(`| \`${escapeCell(field.pattern)}\` | ${escapeCell(field.reason)} |`);
  }

  lines.push('');
  return lines.join('\n');
}

const registry = parseSimpleYaml(await readFile(registryPath, 'utf8'));
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, renderRegistry(registry));
console.log(`Generated ${path.relative(rootDir, outputPath)}`);
