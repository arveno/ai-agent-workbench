import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = path.join(rootDir, 'contracts/schemas');
const outputPath = path.join(rootDir, 'contracts/generated/workbench-contract.ts');

async function listSchemaFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        return listSchemaFiles(entryPath);
      }

      return entry.name.endsWith('.schema.json') ? [entryPath] : [];
    }),
  );

  return files.flat();
}

function toSchemaRelativePath(filePath) {
  return path.relative(schemaDir, filePath).split(path.sep).join('/');
}

const schemaFiles = (await listSchemaFiles(schemaDir)).sort((a, b) =>
  toSchemaRelativePath(a).localeCompare(toSchemaRelativePath(b)),
);

const properties = {};
const required = [];

for (const file of schemaFiles) {
  const schema = JSON.parse(await readFile(file, 'utf8'));
  const schemaRelativePath = toSchemaRelativePath(file);
  const title = schema.title;

  if (!title) {
    throw new Error(`Schema ${schemaRelativePath} must define title for type generation.`);
  }

  const propertyName = `${title[0].toLowerCase()}${title.slice(1)}`;
  properties[propertyName] = { $ref: schemaRelativePath };
  required.push(propertyName);
}

const aggregateSchema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'https://ai-agent-workbench.local/contracts/workbench-contract.schema.json',
  title: 'WorkbenchContract',
  type: 'object',
  additionalProperties: false,
  required,
  properties,
};

const output = await compile(aggregateSchema, 'WorkbenchContract', {
  bannerComment: [
    '/**',
    ' * GENERATED FILE. Do not edit directly.',
    ' * Source: contracts/schemas schema tree',
    ' * Generated by: node scripts/generate-contract-types.mjs',
    ' */',
  ].join('\n'),
  cwd: schemaDir,
  additionalProperties: false,
  declareExternallyReferenced: true,
  enableConstEnums: false,
  format: true,
  style: {
    printWidth: 100,
    semi: true,
    singleQuote: true,
    trailingComma: 'all',
  },
  unreachableDefinitions: true,
  unknownAny: true,
});

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output);
console.log(`Generated ${path.relative(rootDir, outputPath)}`);
