import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = path.join(rootDir, 'contracts/schemas');
const outputPath = path.join(rootDir, 'contracts/generated/workbench-contract.ts');

function pascalCase(value) {
  return String(value)
    .replace(/\.schema\.json$/, '')
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join('');
}

function stringLiteral(value) {
  return JSON.stringify(value);
}

function refToTypeName(ref) {
  const [filePart, fragment = ''] = ref.split('#');
  if (fragment.includes('/$defs/')) {
    return fragment.split('/').at(-1);
  }
  if (filePart) {
    return pascalCase(path.basename(filePart));
  }
  throw new Error(`Unsupported local ref without $defs name: ${ref}`);
}

function schemaToType(schema) {
  if (schema.$ref) return refToTypeName(schema.$ref);
  if (schema.anyOf) return schema.anyOf.map(schemaToType).join(' | ');
  if (schema.oneOf) return schema.oneOf.map(schemaToType).join(' | ');
  if (schema.const !== undefined) return stringLiteral(schema.const);
  if (schema.enum) return schema.enum.map(stringLiteral).join(' | ');

  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => schemaToType({ ...schema, type })).join(' | ');
  }

  switch (schema.type) {
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `${schemaToType(schema.items ?? {})}[]`;
    case 'object':
      if (schema.properties) return 'Record<string, unknown>';
      return 'Record<string, unknown>';
    default:
      return 'unknown';
  }
}

function renderComment(description, indent = '') {
  if (!description) return [];
  return [`${indent}/** ${description.replace(/\*\//g, '* /')} */`];
}

function renderInterface(name, schema) {
  if (schema.enum) {
    return [
      ...renderComment(schema.description),
      `export type ${name} = ${schemaToType(schema)};`,
      '',
    ].join('\n');
  }

  if (schema.type !== 'object' || !schema.properties) {
    return [
      ...renderComment(schema.description),
      `export type ${name} = ${schemaToType(schema)};`,
      '',
    ].join('\n');
  }

  const required = new Set(schema.required ?? []);
  const lines = [...renderComment(schema.description), `export interface ${name} {`];

  for (const [propertyName, propertySchema] of Object.entries(schema.properties)) {
    lines.push(...renderComment(propertySchema.description, '  '));
    const optional = required.has(propertyName) ? '' : '?';
    lines.push(`  ${propertyName}${optional}: ${schemaToType(propertySchema)};`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

const schemaFiles = (await readdir(schemaDir))
  .filter((file) => file.endsWith('.schema.json'))
  .sort();

const schemas = [];
for (const file of schemaFiles) {
  const schemaPath = path.join(schemaDir, file);
  const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
  schemas.push({ file, schema, rootName: schema.title || pascalCase(file) });
}

const rendered = [];
const emitted = new Set();

for (const { schema } of schemas) {
  for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
    if (emitted.has(name)) continue;
    emitted.add(name);
    rendered.push(renderInterface(name, definition));
  }
}

for (const { rootName, schema } of schemas) {
  if (emitted.has(rootName)) continue;
  emitted.add(rootName);
  rendered.push(renderInterface(rootName, schema));
}

const output = [
  '/**',
  ' * GENERATED FILE. Do not edit directly.',
  ' * Source: contracts/schemas/*.schema.json',
  ' * Generated by: node scripts/generate-contract-types.mjs',
  ' */',
  '',
  ...rendered,
].join('\n');

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output);
console.log(`Generated ${path.relative(rootDir, outputPath)}`);
